export function getTranslation(lang: Language, key: keyof typeof translations['en'], params?: Record<string, string | number>): string {
  let text = translations[lang]?.[key] || translations['en'][key] || String(key);
  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      text = text.replace(`{${paramKey}}`, String(paramVal));
    });
  }
  return text;
}
